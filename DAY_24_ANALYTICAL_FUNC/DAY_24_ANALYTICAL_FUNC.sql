-- Q.1. WAQD top salaries
    
    WITH TOP_SAL
    AS 
    (   SELECT EMPLOYEE_ID, FIRST_NAME, LAST_NAME, SALARY,DEPARTMENT_ID,
        DENSE_RANK() OVER (ORDER BY SALARY DESC) AS RNK
        FROM EMPLOYEES
    )
    
    SELECT * 
    FROM TOP_SAL
    WHERE RNK <= 3;
	
-- Q.2. WAQD departmentwise top 3 salaries

	WITH TOP_SAL
	AS 
	(	SELECT EMPLOYEE_ID , FIRST_NAME, LAST_NAME, DEPARTMENT_ID , SALARY,
		DENSE_RANK() OVER (PARTITION BY DEPARTMENT_ID ORDER BY SALARY DESC) AS RNK
		FROM EMPLOYEES
	)
	
	SELECT * 
	FROM TOP_SAL
	WHERE RNK <= 3;
	
--Q.3 WAQTD bottom 3 salaries
	
	WITH BOTTOM_SAL
	AS
	(	SELECT EMPLOYEE_ID , FIRST_NAME, LAST_NAME , DEPARTMENT_ID, SALARY, 
		DENSE_RANK() OVER (ORDER BY SALARY ) AS RNK
		FROM EMPLOYEES
	)
	
	SELECT * 
	FROM BOTTOM_SAL
	WHERE RNK <= 3;

-- Q.4. WAQD departmentwise bottom 3 salaries

	WITH BOTTOM_SAL
	AS
	(	SELECT EMPLOYEE_ID, FIRST_NAME, LAST_NAME, DEPARTMENT_ID, SALARY,
		DENSE_RANK() OVER (PARTITION BY DEPARTMENT_ID ORDER BY SALARY ASC) AS B_RNK
		FROM EMPLOYEES
	)
	
	SELECT * FROM BOTTOM_SAL 
	WHERE B_RNK <= 3;
	
-- Q.5. WAQD Top 3rd salary

	WITH T_SAL
	AS
	(	SELECT EMPLOYEE_ID, FIRST_NAME, LAST_NAME, DEPARTMENT_ID, SALARY,
		DENSE_RANK() OVER (ORDER BY SALARY DESC) AS T_RNK
		FROM EMPLOYEES
	)
	
	SELECT * FROM T_SAL 
	WHERE T_RNK = 3;

-- Q.6. WAQD departmentwise top 3rd salary

