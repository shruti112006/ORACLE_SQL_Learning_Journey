-- 1. WAQD total annual salary of employees with commission and sort them
	SELECT EMPLOYEE_ID,SALARY ,
			CASE WHEN COMMISSION_PCT IS  NULL THEN (SALARY*12)
			  WHEN COMMISSION_PCT IS NOT NULL THEN (SALARY*12*COMMISSION_PCT)
			END AS TOT_ANN_SAL
	FROM EMPLOYEES
	ORDER BY TOT_ANN_SAL; 
	
-- 2.WAQTD EMPLOYEES DETAILS WITH THERE GRADE AND ALSO FILETR THE GRADE WHERE SALARY IS GREATER THEN 5000
	SELECT FIRST_NAME , LAST_NAME ,SALARY,
			CASE WHEN SALARY BETWEEN 1000 AND 5000 THEN 'POOR'
				 WHEN SALARY BETWEEN 5001 AND 8000 THEN 'AVG'
			END AS SAL_GRADE
	FROM EMPLOYEES 
	WHERE 	CASE WHEN SALARY BETWEEN 1000 AND 5000 THEN 'POOR'
				 WHEN SALARY BETWEEN 5001 AND 8000 THEN 'AVG'
			END IS NOT NULL
	AND (SALARY > 5000);
			 
-- 3.WAQTD EMPLOYEE NAME, EXPERIENCE IN YEARS AND EXPERIENCE GRADE USING CASE STATEMENT.		 
	SELECT FIRST_NAME , LAST_NAME ,
	ROUND(MONTHS_BETWEEN(SYSDATE,HIRE_DATE)/12)  AS EXPERIENCED,
	 CASE 
		 WHEN MONTHS_BETWEEN(SYSDATE, HIRE_DATE)/12 < 16 THEN 'FRESHER'
		 WHEN MONTHS_BETWEEN(SYSDATE, HIRE_DATE)/12 BETWEEN 17 AND 24 THEN 'MID'
		 ELSE 'SENIOR'
	 END EXP_TITLE
	FROM EMPLOYEES; 
	
-- 4.WAQTD REGION NAME, NUMBER OF COUNTRIES IN EACH REGION, AND TELL THE REGION AS LARGE OR SMALL BASED ON COUNTRY COUNT.

	SELECT R.REGION_NAME,
			COUNT(C.COUNTRY_ID) AS COUNTRY_COUNT,
			CASE
			   WHEN COUNT(C.COUNTRY_ID) > 5 THEN ' LARGE REGION '
			   ELSE ' SMALL REGION '
			END AS REGION_SIZE
	FROM REGIONS R
	JOIN COUNTRIES C ON R.REGION_ID = C.REGION_ID
	GROUP BY R.REGION_NAME;

				
-- 5.WAQTD EMPLOYEE DETAILS AND DISPLAY ONLY EMPLOYEES HAVING ‘GOOD SAL’ GRADE.
	SELECT EMPLOYEE_ID, FIRST_NAME, LAST_NAME , SALARY, 
				CASE WHEN SALARY BETWEEN 0 AND 2000 THEN 'POOR SAL'
				WHEN SALARY BETWEEN 2001 AND 5000 THEN 'AVG SAL'
				WHEN SALARY BETWEEN 5001 AND 10000 THEN 'GOOD SAL'
				WHEN SALARY BETWEEN 10001 AND 20000 THEN 'BETTER SAL'
				ELSE 'BEST SAL' 
				END AS SAL_GRADE
	FROM EMPLOYEES 
	WHERE (
				CASE WHEN SALARY BETWEEN 5001 AND 10000 THEN 'GOOD SAL'
				END) = 'GOOD SAL' ;
				

-- 6.WAQTD CITY, TOTAL SALARY AND SALARY CATEGORY, DISPLAY ONLY HIGH-PAY CITIES.
	SELECT L.CITY , SUM(E.SALARY) AS TOTAL_SAL,
	CASE 
	   WHEN SUM(SALARY) >150000 THEN ' HIGHT PAY CITY '
	   ELSE ' LOW PAY CITY '
	   END AS DETAILS
	FROM EMPLOYEES E JOIN DEPARTMENTS D
	ON (E.DEPARTMENT_ID = D.DEPARTMENT_ID )
	JOIN LOCATIONS L 
	ON(D.LOCATION_ID = L .LOCATION_ID)
	GROUP BY L.CITY
	HAVING SUM(E.SALARY) > 100000;

-- 7.WAQTD EMPLOYEE NAME, JOB ID AND CLASSIFY JOB TYPE USING DECODE.
	SELECT CONCAT(CONCAT(FIRST_NAME, ' '), LAST_NAME) AS FULLNAME, JOB_ID,
			DECODE(JOB_ID,
				  'IT_PROG', 'TECH',
				  'SA_REP',  'SALES',
				  'OTHER') AS JOB_TYPE
	FROM EMPLOYEES;

-- 8.WAQTD COUNTRY NAME AND CLASSIFY COUNTRY BASED ON NUMBER OF EMPLOYEES.
	SELECT C.COUNTRY_NAME,
		   COUNT(E.EMPLOYEE_ID) AS EMP_COUNT,
			CASE
			   WHEN COUNT(E.EMPLOYEE_ID) > 30 THEN 'HIGH COUNT'
			   ELSE 'LOW COUNT'
			END AS COUNTRY_STATUS
	FROM EMPLOYEES E
	JOIN DEPARTMENTS D ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
	JOIN LOCATIONS L ON D.LOCATION_ID = L.LOCATION_ID
	JOIN COUNTRIES C ON L.COUNTRY_ID = C.COUNTRY_ID
	GROUP BY C.COUNTRY_NAME
	ORDER BY EMP_COUNT DESC;

				
--9.WAQTD EMPLOYEE DETAILS AND DISPLAY COMMISSION AS 0 FOR EMPLOYEES WHOSE COMMISSION IS NULL.
	SELECT FIRST_NAME, COMMISSION_PCT,
			CASE
			   WHEN COMMISSION_PCT IS NULL THEN 0
			   ELSE COMMISSION_PCT
			END AS COMMISSION
	FROM EMPLOYEES;
		
-- 10.WAQTD EMPLOYEE NAME, HIRE DATE AND DISPLAY WHETHER THE EMPLOYEE JOINED ON A WEEKEND OR A WEEKDAY.
	SELECT FIRST_NAME, HIRE_DATE,TO_CHAR(HIRE_DATE, 'DY')AS WEEK_DAYS,
			CASE
			   WHEN TO_CHAR(HIRE_DATE, 'DY') IN ('SAT','SUN') THEN 'WEEKEND'
			   ELSE 'WEEKDAY'
			END AS JOIN_DAY
	FROM EMPLOYEES;
	
-- 11.WAQTD EMPLOYEE DETAILS WITH EXPERIENCE GRADE FOR EMPLOYEES WHOSE SALARY MATCHES EMPLOYEES FROM DEPARTMENT 80.
	SELECT FIRST_NAME , LAST_NAME ,DEPARTMENT_ID,
		ROUND(MONTHS_BETWEEN(SYSDATE,HIRE_DATE)/12)  AS EXPERIENCED,
		CASE WHEN MONTHS_BETWEEN(SYSDATE, HIRE_DATE)/12 < 15 THEN 'FRESHER'
			 WHEN MONTHS_BETWEEN(SYSDATE, HIRE_DATE)/12 BETWEEN 16 AND 20 THEN 'MID'
			 ELSE 'SENIOR'
		END AS EXP_GRADE
	FROM EMPLOYEES
	WHERE SALARY IN (SELECT SALARY
				FROM EMPLOYEES
				WHERE DEPARTMENT_ID = 80);

