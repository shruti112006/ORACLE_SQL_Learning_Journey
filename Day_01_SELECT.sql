-- Retrieve data from a database table.

1. --	EMPLOYEE ID, FULLNAME AND EMAIL
	SELECT EMPLOYEE_ID,(FIRST_NAME ||' '|| LAST_NAME) AS FULLNAME, EMAIL
	FROM EMPLOYEES;
	
2.	--FULLNAME AND HIRE DATE
	SELECT (FIRST_NAME ||' '|| LAST_NAME) AS FULLNAME, HIRE_DATE 
	FROM EMPLOYEES;
	
3.	--EMPLOYEE DETAILS in the format 101 works as IT Prog
	SELECT (EMPLOYEE_ID ||' WORKS AS '|| JOB_ID ) AS EMPLOYEE_DETAILS
	FROM EMPLOYEES;
	
4. --FULLNAME AND ANNUAL SALARY
	SELECT	(FIRST_NAME ||' '|| LAST_NAME) AS FULLNAME, (SALARY * 12) AS ANNUAL_SAL
	FROM EMPLOYEES;
	
5.	--FULLNAME AND PERDAY SALARY
	SELECT	(FIRST_NAME ||' '|| LAST_NAME) AS FULLNAME, (SALARY /30) AS PERDAY_SAL
	FROM EMPLOYEES;
	
6.	--COMMUNICATION INFO OF EMP
	SELECT EMPLOYEE_ID, (EMAIL ||' AND '|| PHONE_NUMBER) AS COMMUNICATION_METHODS
	FROM EMPLOYEES;
	
7.	--DISPLAY HEAD OF THE DEPARTMENT
	SELECT ('HEAD OF '|| DEPARTMENT_NAME||' IS '||MANAGER_ID ) AS HOD
	FROM DEPARTMENTS;
	
8.	--DEPARTMENT DETAILS AS DEPART ID, NAME LOCATION IS 1700
	SELECT DEPARTMENT_ID , (DEPARTMENT_NAME||' LOCATION IS '|| LOCATION_ID) AS LOC_DETAILS
	FROM DEPARTMENTS;
	
9.	--WAQD "firstname belongs to department 10"
	SELECT (FIRST_NAME||' BELONGS TO DEPARTMENT '|| DEPARTMENT_ID) DEP_DETAILS 
	FROM EMPLOYEES;
	
10.	--COMMISSION RATE AS commission of neena is: .2
	SELECT ('COMMISSION OF '|| FIRST_NAME || 'IS : '||COMMISSION_PCT ) AS COMMISSION_RATE
	FROM EMPLOYEES;	 
	
11.	SELECT  MANAGER_ID, DEPARTMENT_NAME, LOCATION_ID
	FROM DEPARTMENTS;
	
12.	--FULLNAME, SALARY INCREASED BY 20%
	SELECT (FIRST_NAME ||' '||LAST_NAME) AS FULLNAME, (SALARY + (SALARY*0.20)) AS INCREMENTS
	FROM EMPLOYEES;
	
13.	--FULLNAME, SALARY INCREASED BY 10% , NEW ANNUAL SALARY AS NEW_ANNUAL_SAL
	SELECT (FIRST_NAME ||' '||LAST_NAME) AS FULLNAME,(SALARY + (SALARY*0.10)) AS INCREMENTS, (SALARY + (SALARY*0.10))*12 AS NEW_ANNUAL_SAL 
	FROM EMPLOYEES;
	
14.	--WAQD reduce salary by 10% and display it AS 10, 24000, decreased by 10%,loss 
	SELECT EMPLOYEE_ID,SALARY, (SALARY - (SALARY*0.1)) AS DECREASED, (SALARY - (SALARY *0.9))AS LOSS 
	FROM EMPLOYEES;
	
15.	--WAQD salary of emp after 5 years 
	SELECT  ('SALARY OF '|| EMPLOYEE_ID ||' AFTER 5 YEARS IS '|| SALARY * 60) AS BANK_BALANCE
	FROM EMPLOYEES;
	
16.	--WAQD Annual commision rate of an employee
	SELECT (EMPLOYEE_ID ||' EARNED '||COMMISSION_PCT *12||' ANNUAL COMMISSION')AS COMMISSION_RATE
	FROM EMPLOYEES;
	
17. --WAQD employeeid hires On  hire date in 10
	SELECT (EMPLOYEE_ID ||' HIRES ON '|| HIRE_DATE ||' IN DEPARTMENT '|| DEPARTMENT_ID) AS HIRING_DETAILS
	FROM EMPLOYEES;
	
18. --WAQD empid works under 101 
	SELECT (EMPLOYEE_ID || ' WORKS UNDER '|| MANAGER_ID) AS MANAGER_DETAILS
	FROM EMPLOYEES;
	
19. --WAQD  DEPT_NAME, DEPT_ID, LOC_ID by using all types of alias 
	SELECT DEPARTMENT_NAME AS DEPT_NAME, DEPARTMENT_ID DEPT_ID, LOCATION_ID AS "LOC_ID"
	FROM DEPARTMENTS;
	
20. --WAQD firstname as fname, lastname as lname, department id as d_id
	SELECT FIRST_NAME AS FNAME, LAST_NAME AS LNAME, DEPARTMENT_ID AS D_ID 	
	FROM EMPLOYEES;
	
21. --WAQD fullname gets 10% commission
	SELECT (FIRST_NAME ||' '||LAST_NAME||' GETS  '||COMMISSION_PCT *100||'% COMMISSION ') AS DETAILS 
	FROM EMPLOYEES;

22. --WAQD departmentid, employeeid and hiredate of all employees
	SELECT DEPARTMENT_ID, EMPLOYEE_ID, HIRE_DATE
	FROM EMPLOYEES;

23. --WAQD 110 joined in department 20 on 01-01-01
	SELECT (EMPLOYEE_ID ||' JOINED IN DEPARTMENT '||DEPARTMENT_ID||' ON '||HIRE_DATE) AS JOINING_DETAILS
	FROM EMPLOYEES;
	
24. --WAQD empid , fullname , quarterly salary
	SELECT EMPLOYEE_ID,(FIRST_NAME || ' '|| LAST_NAME) AS FULLNAME, (SALARY *4) AS QUARTERLY_SALARY
	FROM EMPLOYEES;	

25. -- WAQD details of emp such as EMP_ID, JOB_ID, MANAGER_ID
	SELECT HIRE_DATE , EMPLOYEE_ID AS EMP_ID, JOB_ID , MANAGER_ID 
	FROM EMPLOYEES;