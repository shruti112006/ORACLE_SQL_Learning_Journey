CREATE TABLE EMPLO_JOIN_TRG(
EMP_ID NUMBER(4) ,
FIRST_NAME VARCHAR2(25),
LAST_NAME VARCHAR2(25),
SALARY NUMBER(8),
DEPARTMENT_ID NUMBER(4),
DEPARTMENT_NAME VARCHAR2(25)
);


MERGE INTO EMPLO_JOIN_TRG TRG
USING (SELECT E.EMP_ID,E.FIRST_NAME,E.LAST_NAME,E.SALARY,D.DEPARTMENT_ID,D.DEPARTMENT_NAME
        FROM EMPLO E JOIN DEPT D
        ON(E.DEPARTMENT_ID=D.DEPARTMENT_ID)) SRC
ON(TRG.EMP_ID=SRC.EMP_ID)
WHEN MATCHED THEN 
UPDATE 
SET TRG.FIRST_NAME=SRC.FIRST_NAME,
    TRG.LAST_NAME=SRC.LAST_NAME,
    TRG.SALARY=SRC.SALARY,
    TRG.DEPARTMENT_ID=SRC.DEPARTMENT_ID,
    TRG.DEPARTMENT_NAME=SRC.DEPARTMENT_NAME
   

WHEN NOT MATCHED THEN 
INSERT(EMP_ID,FIRST_NAME,LAST_NAME,SALARY,DEPARTMENT_ID,DEPARTMENT_NAME)
VALUES(SRC.EMP_ID,SRC.FIRST_NAME,SRC.LAST_NAME,SRC.SALARY,SRC.DEPARTMENT_ID,SRC.DEPARTMENT_NAME);
    
SELECT *FROM EMPLO_JOIN_TRG;

