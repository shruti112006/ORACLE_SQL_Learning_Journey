-- 1. WAQD details of those employees whose annual salary is greater than king's annual salary

    SELECT *
    FROM EMPLOYEES 
    WHERE (SALARY * 12) > ANY  (SELECT SALARY * 12
                               FROM EMPLOYEES
                               WHERE LAST_NAME = 'King');
						
-- 2. WAQD details of those employees whose commission percentage is similar as David Lee

    SELECT *
    FROM EMPLOYEES 
    WHERE COMMISSION_PCT  =   (SELECT COMMISSION_PCT
                               FROM EMPLOYEES
                               WHERE FIRST_NAME = 'David'
                               AND LAST_NAME = 'Lee');

-- 3. WAQD details of those employees who were hired in 2008 ,having manager  same as  MARKLE 
    SELECT *
    FROM EMPLOYEES 
    WHERE TO_CHAR(HIRE_DATE,'YYYY') = '2008'
    AND MANAGER_ID = (SELECT MANAGER_ID
                      FROM EMPLOYEES
                      WHERE UPPER(LAST_NAME) = 'MARKLE');

-- 4. WAQD details of those employees who were hired in 2007, having  job  title  
--    similar to steven or james
    SELECT *
    FROM EMPLOYEES 
    WHERE TO_CHAR(HIRE_DATE,'YYYY') = '2007'
    AND JOB_ID IN (SELECT JOB_ID
                  FROM JOBS
                  WHERE LOWER(FIRST_NAME) IN ('steven','james'));

-- 5. WAQD details of those departments which locates in city oxford or TOKYO
    SELECT *
    FROM DEPARTMENTS 
    WHERE LOCATION_ID  IN(SELECT LOCATION_ID
                          FROM LOCATIONS 
                          WHERE UPPER(CITY) IN ('TOKYO','OXFORD' ));

-- 6. WAQD how many countries located per region
    SELECT r.REGION_ID, r.REGION_NAME,
         ( SELECT COUNT(*) 
           FROM COUNTRIES c 
           WHERE c.REGION_ID = r.REGION_ID) AS CNT
    FROM REGIONS r;
                            
-- 7. WAQTD DETAILS OF EMPLOYEES WHOSE SALARY IS GREATER THAN THE AVERAGE 
--  SALARY OF EMPLOYEES IN DEPARTMENT 10 AND LESS THAN ALL EMPLOYEES IN DEPARTMENT 80

	SELECT *
	FROM EMPLOYEES
	WHERE SALARY > (SELECT AVG(SALARY)
					FROM EMPLOYEES
					WHERE DEPARTMENT_ID =10)
	AND SALARY < (SELECT AVG(SALARY)
					FROM EMPLOYEES
					WHERE DEPARTMENT_ID =80);
					
-- 8. WAQTD DEMPARMENT_NAME OF EMPLOYEES WHOSE LOCATION ID IS  NOT EQUAL TO DEPARTMENT FINANACE
    SELECT DEPARTMENT_NAME,LOCATION_ID
    FROM DEPARTMENTS
    WHERE LOCATION_ID NOT IN   (SELECT LOCATION_ID
								FROM DEPARTMENTS
								WHERE DEPARTMENT_NAME = 'Finance');
						 
-- 9.DISPLAY COUNT OF EMPLOYEES WHOSE SALARY IS MORE THAN MINIMUM SALARY IN PARTICULAR DEPARTMENT 
--       (not including null departments)
    SELECT DEPARTMENT_ID, COUNT(*) AS CNT
    FROM EMPLOYEES
    WHERE SALARY > ANY (SELECT MIN(SALARY)
                        FROM EMPLOYEES
                        GROUP BY DEPARTMENT_ID)
    AND DEPARTMENT_ID IS NOT NULL
    GROUP BY DEPARTMENT_ID
    ORDER BY DEPARTMENT_ID;

-- 10. WAQTD EMPLOYEES DETAILS WHOSE SALARY IS GREATER THAN EMPLOYEES WORKING IN DEPARTMENT_ID 30
    SELECT *
    FROM EMPLOYEES
    WHERE SALARY > ANY(SELECT SALARY
                    FROM EMPLOYEES
                    WHERE DEPARTMENT_ID = 30);
					
-- 11.WAQTD EMPLOYEES DETAILS WHOSE ADRESS IS 2004 Charade Rd USING SUBQUREY 
    SELECT  EMPLOYEE_ID , CONCAT(CONCAT(FIRST_NAME,' '),LAST_NAME) AS FULL_NAME,
            DEPARTMENT_ID, SALARY
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID IN (SELECT DEPARTMENT_ID
                           FROM DEPARTMENTS
                           WHERE LOCATION_ID = (SELECT LOCATION_ID
                                                FROM LOCATIONS
                                                WHERE STREET_ADDRESS = '2004 Charade Rd' ));

-- 12. WAQTD EMPLOYEE DETAILS WHO IS WORKING IN IT DEPARTMENT_NAME
    SELECT EMPLOYEE_ID ,(FIRST_NAME||' '||LAST_NAME)AS FULLNAME ,JOB_ID, DEPARTMENT_ID
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = (SELECT DEPARTMENT_ID
                            FROM DEPARTMENTS
                            WHERE DEPARTMENT_NAME = 'IT');
												
-- 13. WAQTD EMPLOYEE COUNT WHO IS WORKING IN IT DEPARTMENT_NAME
    SELECT JOB_ID, COUNT(*) AS EMP_CNT
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = (SELECT DEPARTMENT_ID
                            FROM DEPARTMENTS
                            WHERE DEPARTMENT_NAME = 'IT')
    GROUP BY JOB_ID;

-- 14. DISPLAY DEPARTMENTS NAME THAT HAVE MORE  EMPLOYEES THAN DEPARTMENT 30
	SELECT DEPARTMENT_ID,DEPARTMENT_NAME
    FROM EMPLOYEES JOIN DEPARTMENTS 
    USING (DEPARTMENT_ID)
    GROUP BY DEPARTMENT_ID,DEPARTMENT_NAME
    HAVING COUNT(*) > (
          SELECT COUNT(*)
          FROM EMPLOYEES
          WHERE DEPARTMENT_ID = 30);

-- 15.WAQTD EMPLOYEES DEPARTMENT NAMES WERE LOCATION_ID BETWEEN 1700  AND 2000
	--    HAVING COMMISSIONPCT IS NULL
	SELECT * FROM EMPLOYEES 
	WHERE DEPARTMENT_ID  IN (SELECT DEPARTMENT_ID
						 FROM DEPARTMENTS
						 WHERE LOCATION_ID BETWEEN 1700 AND 2000)
	AND COMMISSION_PCT IS NULL ;
	
-- 16.FIND EMPLOYEES (NAME & SALARY) WHO EARN THE HIGHEST SALARY IN THEIR DEPARTMENT, ALONG WITH THE DEPARTMENT NAME.
	SELECT E.EMPLOYEE_ID ,
		   CONCAT(CONCAT(E.FIRST_NAME,' '),E.LAST_NAME) AS FULL_NAME,
		   E.SALARY,
		   D.DEPARTMENT_NAME
	FROM EMPLOYEES E
	INNER JOIN DEPARTMENTS D
		ON (E.DEPARTMENT_ID = D.DEPARTMENT_ID)
	WHERE E.SALARY = (SELECT MAX(SALARY)
					FROM EMPLOYEES
					WHERE DEPARTMENT_ID = E.DEPARTMENT_ID);
    
-- 17. WAQD DETAILS OF EMPLOYEES WHO HAS SAME SALARY AS DAVID AUSTIN
    
    SELECT  EMPLOYEE_ID, CONCAT(CONCAT(FIRST_NAME,' '), LAST_NAME) AS FULL_NAME,
            SALARY
    FROM EMPLOYEES
    WHERE SALARY = (SELECT SALARY
                    FROM EMPLOYEES
                    WHERE FIRST_NAME = 'David' AND LAST_NAME = 'Austin');
      
-- 18. WAQD DETAILS OF EMPLOYEES WHO ARE HIRED ON SAME DAY THAT JULIA  HIRED

    SELECT *
    FROM EMPLOYEES
    WHERE HIRE_DATE IN (SELECT HIRE_DATE
                        FROM EMPLOYEES
                        WHERE UPPER(FIRST_NAME) = 'JULIA');

--19.DISPLAY EMPLOYEES WHO EARN MORE THAN THE AVERAGE SALARY
	SELECT EMPLOYEE_ID,CONCAT(CONCAT(FIRST_NAME,' '),LAST_NAME)AS FULL_NAME
	FROM EMPLOYEES
	WHERE SALARY > (SELECT AVG(SALARY)
				  FROM EMPLOYEES);
				  
      
-- 20.DISPLAY EMPLOYEES HIRED AFTER THE MOST RECENTLY HIRED EMPLOYEES IN DEPARTMENT 90
	SELECT EMPLOYEE_ID, FIRST_NAME, HIRE_DATE
	FROM EMPLOYEES
	WHERE HIRE_DATE > (SELECT MAX(HIRE_DATE)
					   FROM EMPLOYEES
					   WHERE DEPARTMENT_ID=90);