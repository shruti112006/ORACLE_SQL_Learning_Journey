-- Q.1 Find department wise employee count and avg salary 

	WITH EMP_CNT
	AS (
		SELECT DEPARTMENT_ID , COUNT (*) AS CNT
		FROM EMPLOYEES
		GROUP BY DEPARTMENT_ID
		),
	
		AVG_SAL
	AS(
		SELECT DEPARTMENT_ID , ROUND(AVG(SALARY),2) AS AVERAGE_SAL
		FROM EMPLOYEES
		GROUP BY DEPARTMENT_ID )
	
	SELECT * 
	FROM EMP_CNT JOIN AVG_SAL
	USING (DEPARTMENT_ID);

-- Q.2. Find employees with experience less than 20 and belongs to department Sales

	WITH EMP_EXP
	AS (
		SELECT EMPLOYEE_ID, ROUND(MONTHS_BETWEEN(SYSDATE, HIRE_DATE) /12, 0) AS EXPERIENCE
		FROM EMPLOYEES
		)
	
	SELECT E.EMPLOYEE_ID , E.FIRST_NAME, E.LAST_NAME, E.DEPARTMENT_ID, X.EXPERIENCE
	FROM EMPLOYEES E JOIN EMP_EXP X
	ON (E.EMPLOYEE_ID = X.EMPLOYEE_ID)
	WHERE X.EXPERIENCE < 20
    AND DEPARTMENT_ID = (SELECT DEPARTMENT_ID
                         FROM DEPARTMENTS
                         WHERE UPPER(DEPARTMENT_NAME) ='SALES');
						 
-- Q.3 Find total salary of all departments

	WITH TOTAL_SAL
	AS (
		SELECT DEPARTMENT_ID, SUM(SALARY) AS TOTAL_SAL
		FROM EMPLOYEES
		GROUP BY DEPARTMENT_ID
		)
	
	SELECT D.DEPARTMENT_ID, D.DEPARTMENT_NAME, T.TOTAL_SAL
	FROM DEPARTMENTS D LEFT OUTER JOIN TOTAL_SAL T
	ON (D.DEPARTMENT_ID = T.DEPARTMENT_ID);
		
-- Q.4 FIND HIGHEST AND SECOND HIGHEST SALARY OF EACH DEPARTMENT

	WITH HIGH_SAL 
	AS (
		SELECT DEPARTMENT_ID,MAX(SALARY) AS HIGH_SAL
		FROM EMPLOYEES
		GROUP BY DEPARTMENT_ID
		),
	SECOND_HIGH
	AS (
		SELECT E.DEPARTMENT_ID, MAX(E.SALARY) AS SECOND_HIGH_SAL
		FROM EMPLOYEES E
		WHERE E.SALARY < (SELECT H.HIGH_SAL
						  FROM HIGH_SAL H
						  WHERE H.DEPARTMENT_ID = E.DEPARTMENT_ID)
		GROUP BY E.DEPARTMENT_ID
		)
		
	SELECT H.DEPARTMENT_ID,H.HIGH_SAL,S.SECOND_HIGH_SAL
	FROM HIGH_SAL H JOIN SECOND_HIGH S
	ON(H.DEPARTMENT_ID = S.DEPARTMENT_ID)    
	ORDER BY DEPARTMENT_ID ;

--Q.5 Find employees who earn more than or equal to average salary of their department and less than or equal to 10000

    WITH DISPLAY_DEPT
    AS (
        SELECT DEPARTMENT_ID, AVG(SALARY)AS AVG_SAL
        FROM EMPLOYEES
        GROUP BY DEPARTMENT_ID
        ),
    EMP_DETAILS
    AS  (
        SELECT DEPARTMENT_ID,CONCAT(CONCAT(FIRST_NAME,' '),LAST_NAME) AS FULL_NAME,SALARY
        FROM EMPLOYEES
            )
     
    SELECT D.DEPARTMENT_ID,S.FULL_NAME,S.SALARY
    FROM DISPLAY_DEPT D JOIN EMP_DETAILS S
    ON (D.DEPARTMENT_ID=S.DEPARTMENT_ID) 
    WHERE  S.SALARY BETWEEN D.AVG_SAL
    AND 10000
    ORDER BY D.DEPARTMENT_ID;
	
	
