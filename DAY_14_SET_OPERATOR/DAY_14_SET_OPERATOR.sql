-- 9.WAQD department details which contains at least 3 different job types
--   including the department of steven king
   
	SELECT D.DEPARTMENT_ID, DEPARTMENT_NAME 
    FROM DEPARTMENTS D JOIN EMPLOYEES E
    ON (E.DEPARTMENT_ID = D.DEPARTMENT_ID)
    GROUP BY D.DEPARTMENT_ID, D.DEPARTMENT_NAME
    HAVING COUNT(*)>= 3
    UNION
    SELECT D.DEPARTMENT_ID, DEPARTMENT_NAME
    FROM DEPARTMENTS D 
    WHERE DEPARTMENT_ID  = (SELECT DEPARTMENT_ID FROM EMPLOYEES
                            WHERE UPPER(FIRST_NAME) = 'STEVEN'
                            AND LOWER(LAST_NAME) = 'king');
                              
-- 10. WAQD details of employees who works in department 20, 70, or in finance 

    SELECT * FROM EMPLOYEES
    WHERE DEPARTMENT_ID IN (20,70)
