-- 1. WAQD all manager's id without duplications  --(1 null entry)
	SELECT MANAGER_ID FROM EMPLOYEES
	UNION
	SELECT MANAGER_ID FROM DEPARTMENTS
	ORDER BY MANAGER_ID;

-- 2. WAQD departmentid and their manager id  in employees table only
    SELECT DEPARTMENT_ID, MANAGER_ID FROM EMPLOYEES
    MINUS
    SELECT DEPARTMENT_ID, MANAGER_ID FROM DEPARTMENTS;
	
-- 3. WAQD city and state province of those locations in which their is  no any departments
    SELECT CITY, STATE_PROVINCE
    FROM LOCATIONS
    WHERE LOCATION_ID IN (SELECT LOCATION_ID FROM LOCATIONS
                           MINUS
                           SELECT LOCATION_ID FROM DEPARTMENTS);

-- 4. WAQD employees security password such as  $$$$100stev****  for those employees 
--    who does not have any job history
    SELECT  EMPLOYEE_ID, CONCAT(CONCAT(FIRST_NAME,' '),LAST_NAME) AS FULLNAME,
            JOB_ID, SALARY,
            RPAD(LPAD(CONCAT(EMPLOYEE_ID,SUBSTR(FIRST_NAME,1,4)),9,'$'),11,'*')AS SECURITY_PASSWORD
    FROM EMPLOYEES
    WHERE EMPLOYEE_ID NOT IN (SELECT EMPLOYEE_ID FROM EMPLOYEES
                              INTERSECT
                              SELECT EMPLOYEE_ID FROM JOB_HISTORY )
    ORDER BY EMPLOYEE_ID;
	
-- 5. WAQD those professions whose records not in job history
    SELECT JOB_ID FROM EMPLOYEES
    GROUP BY JOB_ID
    MINUS
    SELECT JOB_ID FROM JOB_HISTORY 
    GROUP BY JOB_ID
    ORDER BY JOB_ID;
	 
-- 6. WAQD cityname,countryname and region name of those employees
--    whose professions whose records are in job history
    
	SELECT  D.DEPARTMENT_ID, L.CITY, C.COUNTRY_NAME, R.REGION_NAME
    FROM REGIONS R  JOIN COUNTRIES C
    ON (R.REGION_ID = C.REGION_ID )
    JOIN LOCATIONS L
    ON(C.COUNTRY_ID = L.COUNTRY_ID)
    JOIN DEPARTMENTS D
    ON (L.LOCATION_ID = D.LOCATION_ID)
    WHERE D.DEPARTMENT_ID = ANY (SELECT DEPARTMENT_ID
                                 FROM EMPLOYEES
                                 WHERE JOB_ID IN (SELECT JOB_ID FROM EMPLOYEES
                                                  INTERSECT
                                                  SELECT JOB_ID FROM JOB_HISTORY ));

-- 7. WAQD maximum salary of a particular job profession  whose record not in history and
--    whose employee get commission 
    
	SELECT * FROM JOBS
    WHERE JOB_ID IN (SELECT JOB_ID FROM JOBS
                     MINUS
                     SELECT JOB_ID FROM JOB_HISTORY)
                     
    AND JOB_ID NOT IN (SELECT JOB_ID FROM EMPLOYEES
                       WHERE COMMISSION_PCT IS NOT NULL);   
     
--8.WAQD details of Employees earning more than 150,000 annually OR working as IT Programmer
   
