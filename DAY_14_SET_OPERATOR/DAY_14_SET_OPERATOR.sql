    SELECT * FROM EMPLOYEES
    WHERE DEPARTMENT_ID = (SELECT DEPARTMENT_ID
                           FROM DEPARTMENTS WHERE DEPARTMENT_NAME ='Finance');

-- 11. WAQD details of employees who was hired before 2004  but  yet his profession doesn't change
    
	SELECT EMPLOYEE_ID, CONCAT(CONCAT(FIRST_NAME,' '),LAST_NAME) AS FULLNAME,
           HIRE_DATE, JOB_ID, SALARY
    FROM EMPLOYEES                     
    WHERE TO_CHAR(HIRE_DATE, 'YYYY') < '2004'  --14
    MINUS
    SELECT EMPLOYEE_ID, CONCAT(CONCAT(FIRST_NAME,' '),LAST_NAME) AS FULLNAME,
           HIRE_DATE, JOB_ID, SALARY 
    FROM EMPLOYEES
    WHERE EMPLOYEE_ID IN (SELECT EMPLOYEE_ID 
                          FROM JOB_HISTORY
                          WHERE TO_CHAR(START_DATE, 'YYYY') < '2004');  -- 3 unique ids						   

-- 12.WAQD details of employees who are managers and get commission

    SELECT * FROM EMPLOYEES
    WHERE EMPLOYEE_ID IN (SELECT DISTINCT E.EMPLOYEE_ID
                          FROM EMPLOYEES E JOIN EMPLOYEES M
                          ON (E.EMPLOYEE_ID = M.MANAGER_ID))
    INTERSECT
    SELECT * FROM EMPLOYEES
    WHERE COMMISSION_PCT IS NOT NULL;

-- 13.WAQD details of employees whose salary is greater than or equals to 8000 and less 
--  than or equals to 10000 and working in department 'SHIPPPING' but does not get any commission 
   
   SELECT EMPLOYEE_ID,DEPARTMENT_ID ,COMMISSION_PCT FROM EMPLOYEES
    WHERE SALARY IN (SELECT SALARY
                     FROM EMPLOYEES 
                     WHERE SALARY BETWEEN 8000 AND 10000)
    INTERSECT
    SELECT EMPLOYEE_ID,DEPARTMENT_ID,COMMISSION_PCT  FROM EMPLOYEES
    WHERE DEPARTMENT_ID IN (SELECT DEPARTMENT_ID
                            FROM DEPARTMENTS
                            WHERE DEPARTMENT_NAME = 'Shipping')
    MINUS 
    SELECT EMPLOYEE_ID,DEPARTMENT_ID,COMMISSION_PCT FROM EMPLOYEES
    WHERE COMMISSION_PCT IS NOT NULL;

-- 14.FIND EMPLOYEES WHO WORK IN DEPARTMENT 50 OR 90 BUT HAVE NEVER EARNED COMMISSION.
    SELECT EMPLOYEE_ID,DEPARTMENT_ID,FIRST_NAME
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID IN(50,90)
    MINUS
    SELECT EMPLOYEE_ID,DEPARTMENT_ID,FIRST_NAME
    FROM EMPLOYEES
    WHERE COMMISSION_PCT IS NOT NULL;

--15.FIND EMPLOYEES WHO WORK IN 60 OR SALES ALON WITH THOSE WHO JOINED IN 2008
--BUT NEVER HAD ANY JOB CHANGE IN JOB_HISTORY.

    SELECT EMPLOYEE_ID ,DEPARTMENT_ID , HIRE_DATE , JOB_ID
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID IN (60,80)
    UNION ALL
    SELECT EMPLOYEE_ID ,DEPARTMENT_ID , HIRE_DATE , JOB_ID
    FROM EMPLOYEES
    WHERE TO_CHAR(HIRE_DATE, 'YYYY') = '2008'
    INTERSECT
    SELECT EMPLOYEE_ID ,DEPARTMENT_ID , START_DATE , JOB_ID
    FROM JOB_HISTORY;

-- 16. DEPT AVERAGE SALARY ABOVE 8000 OR BELOW 4000
    SELECT DEPARTMENT_ID
    FROM EMPLOYEES
    GROUP BY DEPARTMENT_ID
    HAVING AVG(SALARY) > 8000
    UNION ALL
    SELECT DEPARTMENT_ID
    FROM EMPLOYEES
    GROUP BY DEPARTMENT_ID HAVING AVG (SALARY) < 4000;
	
-- 17. FIND EMPLOYEES WHO HAVE WORKED IN BOTH DEPARTMENT 60 AND 80 AT ANY POINT OF TIME.
    SELECT EMPLOYEE_ID,HIRE_DATE,JOB_ID
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID IN(60,80)
    
    UNION
    
    SELECT EMPLOYEE_ID,START_DATE,JOB_ID
    FROM JOB_HISTORY
    WHERE DEPARTMENT_ID IN(60,80);
	
-- 18.EMPLOYEES LOCATED AT UK OR EG
	SELECT EMPLOYEE_ID
	FROM EMPLOYEES E
	JOIN DEPARTMENTS D ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
	JOIN LOCATIONS L ON D.LOCATION_ID = L.LOCATION_ID
	WHERE L.COUNTRY_ID = 'UK'
	UNION
	SELECT EMPLOYEE_ID
	FROM EMPLOYEES E
	RIGHT OUTER JOIN DEPARTMENTS D ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
	RIGHT OUTER JOIN LOCATIONS L ON D.LOCATION_ID = L.LOCATION_ID
	WHERE L.COUNTRY_ID = 'EG';
	
