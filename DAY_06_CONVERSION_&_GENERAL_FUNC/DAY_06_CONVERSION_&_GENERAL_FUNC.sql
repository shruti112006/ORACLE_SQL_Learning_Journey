-- 1. SIMPLE DATE CONVERSION
    SELECT  EMPLOYEE_ID,SALARY, TO_DATE(HIRE_DATE, 'DD-MM-YY') AS CONVERSION_DATE
    FROM EMPLOYEES
    WHERE SALARY > 10000;
	
-- 2. details of emp hired on sunday, jul 2004
	SELECT EMPLOYEE_ID, TO_CHAR(HIRE_DATE , 'DAY-YYYY-MON') AS HIRE_DATE 
    FROM EMPLOYEES
    WHERE SUBSTR(HIRE_DATE,7) = 04
    AND SUBSTR(TO_CHAR(HIRE_DATE , 'DAY-YYYY-MON'),1,6) = 'SUNDAY'
    AND  SUBSTR(TO_CHAR(HIRE_DATE , 'DAY-YYYY-MON'),-3) = 'JUL' ;
	
-- 3. details of emp hired on sunday, apr 2006
	SELECT EMPLOYEE_ID, TO_CHAR(HIRE_DATE , 'DAY-YYYY-MON') AS HIRE_DATE 
    FROM EMPLOYEES
    WHERE SUBSTR(HIRE_DATE,7) = 06
    AND SUBSTR(TO_CHAR(HIRE_DATE , 'DAY-YYYY-MON'),1,6) = 'SUNDAY'
    AND  SUBSTR(TO_CHAR(HIRE_DATE , 'DAY-YYYY-MON'),-3) = 'APR' ;
	
-- 4. details of emp had hired in jul 2007, salary greater than 5000

	SELECT EMPLOYEE_ID, TO_CHAR(HIRE_DATE , 'DAY-MON-YYYY') AS HIRE_DATE 
    FROM EMPLOYEES
    WHERE SUBSTR(HIRE_DATE,7) = 07
    AND SALARY > 5000 ;
	
-- 5. WAQD details of employees who hired on odd month having letter t in email
--		sort it on basis of EMAIL
	SELECT EMPLOYEE_ID, SALARY, TO_CHAR(HIRE_DATE, 'DD/MM/YY') AS HIRE_DATE, EMAIL
	FROM EMPLOYEES
	WHERE  MOD(SUBSTR(HIRE_DATE,4,2), 2) <> 0
	AND EMAIL LIKE '%T%'
    ORDER BY EMAIL;
	
-- 6. WQAD LIST OF EMPLOYEES WHO WERE HIRED IN THE LAST 2 YEARS AND DISPLAY THEIR EXPERIENCE IN YEARS, 
--ORDERED BY EXPERIENCE.

    SELECT CONCAT(CONCAT(FIRST_NAME,' '),LAST_NAME) AS FULL_NAME,
            TO_CHAR(HIRE_DATE,'DD/MON/YY') AS HIRE_DATE,
            ROUND(MONTHS_BETWEEN(SYSDATE,HIRE_DATE)/12,2) AS EXPERIENCE
    FROM EMPLOYEES
    WHERE HIRE_DATE BETWEEN '01-01-2006' AND '31-12-2008'
    ORDER BY EXPERIENCE ;

-- 7. WAQD details of employees like total salary (annual sal with commission) who works in department 50 and 100

	SELECT EMPLOYEE_ID, SALARY , DEPARTMENT_ID,
			(NVL2(COMMISSION_PCT, (SALARY*12) + (SALARY*12*COMMISSION_PCT) ,SALARY*12))AS TOTAL_SAL
	FROM EMPLOYEES
	WHERE DEPARTMENT_ID IN (50,100);
	
-- 8. WAQD details like employeeid,annual salary, commission, compensation of those emp who got commission.;	
        SELECT  EMPLOYEE_ID, 
                (SALARY *12) AS ANNUAL_SAL,
                (SALARY *12 * COMMISSION_PCT)AS COMMISSION,
                (SALARY *12 +(SALARY *12 * COMMISSION_PCT)) AS COMPENSATION
        FROM EMPLOYEES
        WHERE COMMISSION_PCT IS NOT NULL
        ORDER BY COMPENSATION;
	
--9. WAQD TO GIVE 10% SALARY INCREMENT TO EMPLOYEES WHO HAVE MORE THAN 24 YEARS OF EXPERIENCE
	SELECT CONCAT(CONCAT(FIRST_NAME,' '), LAST_NAME) AS FULL_NAME,
            TO_CHAR(HIRE_DATE, 'DD/MM/YY') AS HIRE_DATE,
			ROUND(MONTHS_BETWEEN(SYSDATE,HIRE_DATE)/12)AS EXPERIENCE,SALARY,
			(SALARY*1.1) AS NET_MONTH_SALARY
	FROM EMPLOYEES
	WHERE ROUND(MONTHS_BETWEEN(SYSDATE,HIRE_DATE)/12)>24;

-- 10..WAQD details of employees like employee_id, job descrip, salary, annunal salary
   --  whose job descri contain rep and having annual salary greater than 10000 sort the data on job descr and annual salary
    SELECT EMPLOYEE_ID, JOB_ID, SALARY ,(SALARY *12) AS ANNUAL_SAL
           -- TO_DATE(HIRE_DATE, 'MM-DD-YY')
    FROM EMPLOYEES
    WHERE SUBSTR(JOB_ID,4) ='REP' 
    AND (SALARY * 12) > 10000
    ORDER BY JOB_ID, ANNUAL_SAL;

--  11.WAQD DETAILS OF THOSE EMPLOYEES HIRED AFTER 2009 AND DISPLAY THEIR EXPERIENCE IN MONTHS, 
--  ORDERED BY EXPERIENCE.
    SELECT CONCAT(CONCAT(FIRST_NAME,' '),LAST_NAME) AS FULL_NAME, HIRE_DATE,
             ROUND(MONTHS_BETWEEN(SYSDATE,HIRE_DATE)) AS EXPERIENCE
    FROM EMPLOYEES
    WHERE HIRE_DATE > '31-12-2008'
    ORDER BY EXPERIENCE; 
	

-- 12. WAQD details of employees whose lastname starts with 's' having employee id in between 100 to 215
--      sort it in asc order of firstname
    SELECT FIRST_NAME, LAST_NAME, EMPLOYEE_ID, TO_CHAR(HIRE_DATE, 'YY/MON/DD')
    FROM EMPLOYEES
    WHERE INSTR(LAST_NAME,'S',1) = 1
    AND EMPLOYEE_ID BETWEEN 100 AND 215
    ORDER BY FIRST_NAME ASC;

-- 13. WAQD details of department whose location is  1700 snd make managerid 0 if it has value NULL
	SELECT DEPARTMENT_ID, LOCATION_ID, DEPARTMENT_NAME, NVL(MANAGER_ID, 0) AS MANAGER_id
	FROM DEPARTMENTS
	WHERE LOCATION_ID = 1700;
	
-- 14. WAQD details of employees whose manager is 100 retrieve its hire date in the format of yyyy-mon-dd

    SELECT EMPLOYEE_ID, MANAGER_ID, TO_CHAR(HIRE_DATE, 'YYYY-MON-DD')
    FROM EMPLOYEES
    WHERE MANAGER_ID = 100;

-- 15. WAQD details of employees whose experienece is 20 years format the hire date like 'mon- dd- yy'

    SELECT EMPLOYEE_ID, TO_CHAR(HIRE_DATE, 'MON-DD-YY'),
           TRUNC(MONTHS_BETWEEN(SYSDATE , HIRE_DATE) / 12 ,0)AS EXPERIENCE
    FROM EMPLOYEES
    WHERE TRUNC(MONTHS_BETWEEN(SYSDATE , HIRE_DATE) / 12 ,0) = 20;

-- 16.SORTING EMPLOYEES NAMES WHO WORKING IN DEPARTMENT 80 BASED ON THEIR EXPERIENCE 

    SELECT CONCAT(CONCAT(FIRST_NAME,' '),LAST_NAME)AS FULL_NAME,
            TO_CHAR(HIRE_DATE, 'YYYY'), DEPARTMENT_ID,
            TRUNC(MONTHS_BETWEEN(SYSDATE,HIRE_DATE)/12,1)AS EXPERIENCE
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = 80
    ORDER BY EXPERIENCE DESC;
	
-- 17.WAQD DETAILS OF EMPLOYEES AND THEIR EXPERIENCE AND HIRE_DATE IN THE FORMAT  OF 'MON/YYYY'

	SELECT CONCAT(CONCAT(FIRST_NAME,' '), LAST_NAME) AS FULL_NAME,
			TRUNC(MONTHS_BETWEEN(SYSDATE, HIRE_DATE)/12) AS EXPERIRNCE,
			TO_CHAR(HIRE_DATE,'MON/YYYY') AS HIRE_DATE
	FROM EMPLOYEES;

-- 18. DISPLAY EMPLOYEES FULL NAME AND THEIR PER DAY SALARY IF HE DOESNT GET COMMISSION

    SELECT CONCAT(CONCAT(FIRST_NAME,' '), LAST_NAME) AS FULL_NAME, COMMISSION_PCT,
           NVL(COMMISSION_PCT, ROUND(SALARY/30)) AS PER_DAY
    FROM EMPLOYEES
    WHERE COMMISSION_PCT IS NULL;
	
-- 19. WAQD DETAILS OF EMPLOYEES FULL NAME WHO JOINED IN 2001 AND MUST REPORTING TO ONE MANAGER 
    SELECT CONCAT(CONCAT(FIRST_NAME,' '),LAST_NAME)AS FULL_NAME,
           TO_CHAR(TRUNC(HIRE_DATE,'YEAR'),'YYYY')AS YEAR_DATE,MANAGER_ID
    FROM EMPLOYEES
    WHERE TRUNC(HIRE_DATE,'YEAR') = '01-01-01'
    AND MANAGER_ID IS NOT NULL;
	
-- 20. WAQD DETAILS OF EMPLOYEES WHO HAVE LESS THAN 20 YEARS EXPERIENCE AND SALARY WITH COMMISION
--          IS MORE THAN 12000
    SELECT CONCAT(CONCAT(FIRST_NAME,' '),LAST_NAME)AS FULL_NAME,
            NVL2(COMMISSION_PCT, ROUND(SALARY+(SALARY*COMMISSION_PCT)),SALARY) AS NET_SALARY
    FROM EMPLOYEES
    WHERE ROUND(MONTHS_BETWEEN(SYSDATE,HIRE_DATE)/12)<20
    AND SALARY+(SALARY*COMMISSION_PCT) > 12000;
	
-- 21. WAQD DETAILS OF EMPLOYEES WHO HAVE MORE THAN 20 YEARS EXPERIENCE AND SALARY WITH COMMISION
--          IS MORE THAN 10000
    SELECT CONCAT(CONCAT(FIRST_NAME,' '),LAST_NAME)AS FULL_NAME,
            NVL2(COMMISSION_PCT, ROUND(SALARY+(SALARY*COMMISSION_PCT)),SALARY) AS NET_SALARY
    FROM EMPLOYEES
    WHERE ROUND(MONTHS_BETWEEN(SYSDATE,HIRE_DATE)/12) > 20
    AND SALARY+(SALARY*COMMISSION_PCT) > 10000;
	
-- 22. WAQD details of employees whose joins in 2002 
    SELECT EMPLOYEE_ID, (FIRST_NAME ||' ' ||LAST_NAME)AS FULLNAME, TO_CHAR(HIRE_DATE,'YYYY') AS JOINED_YEAR
    FROM EMPLOYEES
    WHERE SUBSTR(HIRE_DATE, 7) = '02';

-- 23. WAQD details of those emp whose empid is range 111 to 201 including both and display full name if name starts with d
    SELECT EMPLOYEE_ID ,(FIRST_NAME ||' '||LAST_NAME) AS FULLNAME ,
			TO_CHAR(HIRE_DATE,'DD/MM/YYYY') AS HIRE_DATE
	FROM EMPLOYEES
	WHERE EMPLOYEE_ID BETWEEN 111 AND 201
    AND FIRST_NAME LIKE 'D%';
	
-- 24. WAQD details of employees who works in department 60 or 90, having salary greater than or equals to 6000 
--		in the format like firstname in capital, lastname small as fullname hireed year 
	SELECT DEPARTMENT_ID, (CONCAT(UPPER(CONCAT(FIRST_NAME, ' ')) , LOWER(LAST_NAME))) AS FULLNAME, SALARY,
            TO_CHAR(HIRE_DATE,'YYYY') AS HIRED_YEAR
	FROM EMPLOYEES
	WHERE DEPARTMENT_ID IN (60,90)
	AND SALARY >=6000
    ORDER BY HIRED_YEAR;
	
