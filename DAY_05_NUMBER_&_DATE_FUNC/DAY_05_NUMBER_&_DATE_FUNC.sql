-- 1. WAQD perday salary of employees who works in department  30 ROUND it upto 3 digits

    SELECT EMPLOYEE_ID, SALARY, DEPARTMENT_ID , ROUND(SALARY/30,3) AS PERDAY_SAL
    FROM EMPLOYEES
	WHERE DEPARTMENT_ID = 30;
	

-- 2. WAQD details of employees who gets commission. Calculate yearly commission and  ROUND it 

    SELECT EMPLOYEE_ID, FIRST_NAME, LAST_NAME, SALARY, COMMISSION_PCT, (COMMISSION_PCT * 12) AS YEARLY_COMMISSION
    FROM EMPLOYEES
    WHERE COMMISSION_PCT IS NOT NULL;
 
-- 3. WAQD details of employees who works as clerk along with their experience

    SELECT EMPLOYEE_ID, FIRST_NAME, LAST_NAME, SALARY, 
           (ROUND(MONTHS_BETWEEN(SYSDATE, HIRE_DATE)/ 12)) AS EXPERIENCE, JOB_ID
    FROM EMPLOYEES
    WHERE JOB_ID LIKE '%CLERK';
	
-- 4. WAQD details of those employees reports to manager 100, 114 sort them in descending order of experience 

    SELECT EMPLOYEE_ID, FIRST_NAME, LAST_NAME, MANAGER_ID ,
           (ROUND(MONTHS_BETWEEN(SYSDATE, HIRE_DATE)/ 12)) AS EXPERIENCE, JOB_ID
    FROM EMPLOYEES
    WHERE MANAGER_ID IN (100, 114)
    ORDER BY EXPERIENCE DESC, FIRST_NAME;	

-- 5. WAQD details of those employees who joins in 2006. they will get a notification after 3 months from now

    SELECT EMPLOYEE_ID, FIRST_NAME, LAST_NAME, ADD_MONTHS(SYSDATE,3) AS E_NOTIFICATION 
    FROM EMPLOYEES
    WHERE HIRE_DATE LIKE '__%06';

-- 6. WAQD the day if the HR decides to give a holiday on next thursday  to all workers of department 100, 80, 70 

    SELECT EMPLOYEE_ID, DEPARTMENT_ID, (NEXT_DAY( SYSDATE, 'THURSDAY')) AS HOLIDAY 
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID IN (70,80,100);

-- 7. There are interns joined in 2007 in department 50&100. After the completion of their 4 months internship 
--    a completion msg must be given by HR at the end of month. WAQD that day of the month  

    SELECT EMPLOYEE_ID, CONCAT(CONCAT(FIRST_NAME, ' '), LAST_NAME) AS FULLNAME ,HIRE_DATE ,JOB_ID, 
           (LAST_DAY(ADD_MONTHS(HIRE_DATE,4))) AS COMPLETION_DAY
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID IN (50,100)
    AND HIRE_DATE > '31-12-2006'
    ORDER BY HIRE_DATE ;
     

-- 8. The HR decides to give 10% increment to those employees who has 5 years of experience and gets some commission monthly

    SELECT EMPLOYEE_ID, FIRST_NAME, LAST_NAME ,SALARY, 
           ROUND(MONTHS_BETWEEN(SYSDATE, HIRE_DATE)/12 , 2) AS EXPERIENCE,
           (SALARY * 1.1) AS SAL_INCREMENT
    FROM EMPLOYEES
    WHERE ROUND(MONTHS_BETWEEN(SYSDATE, HIRE_DATE)/12 , 2) > 20
    AND COMMISSION_PCT IS NULL; 
     
-- 9. WAQD sorted data of employees on the basis of their experiences in desecnding order

    SELECT EMPLOYEE_ID, FIRST_NAME, LAST_NAME ,SALARY, 
           ROUND(MONTHS_BETWEEN(SYSDATE, HIRE_DATE)/12 , 2) AS EXPERIENCE
    FROM EMPLOYEES
    ORDER BY EXPERIENCE DESC;

-- 10. WAQD details of employees hired in 2006 who works in department 10,20,40 and having salary greater than 5500

    SELECT EMPLOYEE_ID, FIRST_NAME, LAST_NAME ,DEPARTMENT_ID, HIRE_DATE,SALARY ,  
           ROUND(MONTHS_BETWEEN(SYSDATE, HIRE_DATE)/12 , 2) AS EXPERIENCE
    FROM EMPLOYEES
    WHERE SUBSTR(TRUNC(HIRE_DATE, 'YEAR') ,7  ) = '06'
    AND SALARY > 5500;
	
-- 11. WAQD DETAILS OF EMPLOYEES WHO DO NOT REPORT TO MANAGER ID 123, 
--       WERE HIRED IN THE YEAR 2005, AND WHOSE PHONE NUMBER CONTAINS THE DIGITS ‘512’.

    SELECT *
    FROM EMPLOYEES
    WHERE MANAGER_ID NOT IN 123
    AND TRUNC(HIRE_DATE,'YEAR') ='01-01-2005'
    AND PHONE_NUMBER LIKE '%512%';   

-- 12. LIST EMPLOYEES WHOSE FIRST NAME LENGTH IS GREATER THAN 6 AND 
--      ORDER THE RESULT BY NAME LENGTH.

    SELECT CONCAT(CONCAT(FIRST_NAME,' '),LAST_NAME) AS FULLNAME,
            LENGTH(FIRST_NAME) AS LEN_NAME
    FROM EMPLOYEES
    WHERE LENGTH(FIRST_NAME) > 6
    ORDER BY LEN_NAME ;
        
--  13.WAQD DETAILS OF THOSE EMPLOYEES HIRED AFTER 2008 AND DISPLAY THEIR EXPERIENCE IN MONTHS, 
--  ORDERED BY EXPERIENCE.
    SELECT CONCAT(CONCAT(FIRST_NAME,' '),LAST_NAME) AS FULL_NAME, HIRE_DATE,
             ROUND(MONTHS_BETWEEN(SYSDATE,HIRE_DATE)) AS EXPERIENCE
    FROM EMPLOYEES
    WHERE HIRE_DATE > '01-01-2007'
    ORDER BY EXPERIENCE;    

--  14.WAQD details of employees like employee_id, job descrip, salary, annunal salary
   --  whose job descri contain man and having annual salary less than 3000 sort the data on job descr and salary
    SELECT EMPLOYEE_ID, JOB_ID, SALARY ,(SALARY *12) AS ANNUAL_SAL
    FROM EMPLOYEES
    WHERE INSTR(JOB_ID,'M') = 1 
    AND (SALARY * 12) >=3000
    ORDER BY JOB_ID, ANNUAL_SAL;	  
    
-- 15. WAQD reduce salary OF EMP by 10% whose manager is 123 OR email starts with letter k and display it  
	SELECT EMPLOYEE_ID,SALARY, EMAIL, MANAGER_ID, 
        ROUND(SALARY - (SALARY*0.1)) AS DECREASED, ROUND(SALARY - (SALARY *0.9))AS LOSS 
	FROM EMPLOYEES
	WHERE MANAGER_ID = 123
    OR EMAIL LIKE 'K%';

-- 16. THERE ARE SOME SENIOR OR OLD EMPLOYEES IN DEPARTMENT 20 WHO WILL COMPLETE THEIR 30 YEARS IN FURTHER MONTHS.
--     CALCULATE REMAINING MONTHS AFTER WHEN THEY COMPLETE THIER 30 YEARS OF DEDICATION

	SELECT EMPLOYEE_ID, FIRST_NAME, LAST_NAME, DEPARTMENT_ID, HIRE_DATE,
		   TRUNC(360 - ROUND(MONTHS_BETWEEN(SYSDATE,HIRE_DATE),2)) AS REMAINING_MONTHS,
		   ADD_MONTHS(SYSDATE,(360 - ROUND(MONTHS_BETWEEN(SYSDATE,HIRE_DATE),2)) )AS RETIREMENT,
           ROUND(MONTHS_BETWEEN(SYSDATE,HIRE_DATE)/12,2) AS EXPERIENCE
	FROM EMPLOYEES
	WHERE DEPARTMENT_ID = 20
	AND ROUND(MONTHS_BETWEEN(SYSDATE,HIRE_DATE)/12,2) < 30;
        
-- 17. WAQD details of employees who joined after 11 oct 2001 and having salary less than or equal to 7500
	SELECT EMPLOYEE_ID, HIRE_DATE, SALARY
	FROM EMPLOYEES
	WHERE HIRE_DATE > '11-10-01' 
	AND SALARY <= 7500;

-- 18. WAQD details of employees had hired on even year eg..2004,2006.
--     Sort it by hiredate nad firstname

	SELECT EMPLOYEE_ID, HIRE_DATE, JOB_ID
	FROM EMPLOYEES
	WHERE  MOD(SUBSTR(HIRE_DATE,7), 2) = 0
    ORDER BY HIRE_DATE DESC, FIRST_NAME;

-- 19. WAQD details of employees had hired on odd year eg..2005,2007 reporting to manager 100,110,123.
--     Sort it by hiredate nad firstname

	SELECT EMPLOYEE_ID, HIRE_DATE,MANAGER_ID,JOB_ID
	FROM EMPLOYEES
	WHERE  MOD(SUBSTR(HIRE_DATE,7), 2) != 0
	AND MANAGER_ID IN (100,110,123)
    ORDER BY HIRE_DATE DESC, FIRST_NAME;
	
-- 20. WAQD details of employees who hired on even date having salary more than 2000 and less than 6000
--		sort it on basis of salary
	SELECT EMPLOYEE_ID, SALARY, HIRE_DATE
	FROM EMPLOYEES
	WHERE  MOD(SUBSTR(HIRE_DATE,1,2), 2) = 0
	AND SALARY > 2000 
	AND SALARY <6000
    ORDER BY SALARY;
	
-- 21. WAQD details of employees who hired on odd month having letter t in email
--		sort it on basis of EMAIL
	SELECT EMPLOYEE_ID, SALARY, HIRE_DATE, EMAIL
	FROM EMPLOYEES
	WHERE  MOD(SUBSTR(HIRE_DATE,4,2), 2) <> 0
	AND EMAIL LIKE '%T%'
    ORDER BY EMAIL;

-- 22.LIST EMPLOYEES WHO WERE HIRED IN THE LAST 5 YEARS AND DISPLAY THEIR EXPERIENCE IN YEARS, 
--      WHO WORKING IN DEPARTMENT_ID 100 ORDERED BY HIRE DATE.
	SELECT CONCAT(CONCAT(FIRST_NAME,' '),LAST_NAME) AS FULL_NAME,HIRE_DATE,
				 ROUND(MONTHS_BETWEEN(SYSDATE,HIRE_DATE)/12,2) AS EXPERIENCE,DEPARTMENT_ID
	FROM EMPLOYEES
	WHERE HIRE_DATE BETWEEN '01-01-2003' AND '31-12-2008'
	AND DEPARTMENT_ID = 100
	ORDER BY HIRE_DATE;

-- 23. WQAD LIST OF EMPLOYEES WHO WERE HIRED IN THE LAST 3 YEARS AND DISPLAY THEIR EXPERIENCE IN YEARS, 
--ORDERED BY EXPERIENCE.

    SELECT CONCAT(CONCAT(FIRST_NAME,' '),LAST_NAME) AS FULL_NAME,HIRE_DATE,
                 ROUND(MONTHS_BETWEEN(SYSDATE,HIRE_DATE)/12,2) AS EXPERIENCE
    FROM EMPLOYEES
    WHERE HIRE_DATE BETWEEN '01-01-2005' AND '31-12-2008'
    ORDER BY EXPERIENCE ;	

--  24. WAQD DETAILS OF EMPLOYEES LIKE EMPID, PHONE NUMBERS, EMAILS. REMOVING THE DOTS FOR EMPLOYEES WHO 
--      DO NOT BELONG TO DEPARTMENTS 20 AND 100.

    SELECT EMPLOYEE_ID AS EMPID, REPLACE(PHONE_NUMBER,'.','$') AS MODIFIEDNUM, EMAIL
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID NOT IN (20,100);		

-- 25.WAQD reduce salary OF EMP by 10% who had less than 10 years of experience, manager is 123 OR email starts with letter m and 
	--display it in desending order on salary  AND EXPERIENCE  
	SELECT EMPLOYEE_ID,SALARY, EMAIL, MANAGER_ID, 
		   (ROUND(MONTHS_BETWEEN(SYSDATE, HIRE_DATE) /12 )) AS EXPERIENCE,
           (SALARY - (SALARY*0.1)) AS DECREASED, (SALARY - (SALARY *0.9))AS LOSS 
	FROM EMPLOYEES
	WHERE MANAGER_ID = 123
    OR EMAIL LIKE 'M%'
    ORDER BY SALARY;
    
-- 26. WAQD experience of those employees whise department is null
	
	SELECT DEPARTMENT_ID, CONCAT(CONCAT(FIRST_NAME,' '), LAST_NAME) AS FULLNAME,
           ROUND(MONTHS_BETWEEN(SYSDATE,HIRE_DATE) / 12) AS EXP
	FROM EMPLOYEES
	WHERE DEPARTMENT_ID IS NULL;
        
        
        
        
    
        
        
        
        
    
        
        
        
        
        
    
        
        
    
    
      
     
     
     
   
     
     
 