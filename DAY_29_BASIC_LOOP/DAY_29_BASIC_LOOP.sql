-- Q.5. COUNT TOTAL NUMBER OF DIGITS IN A  GIVEN NUMBER 

	SET SERVEROUTPUT ON
	DECLARE
		NO1 NUMBER := &S;
		CNT NUMBER := 0;
	BEGIN
		LOOP
			NO1 := TRUNC(NO1 / 10);
            CNT := CNT + 1;
            DBMS_OUTPUT.PUT_LINE (CNT);
		EXIT WHEN NO1 = 0;
		END LOOP;
        DBMS_OUTPUT.PUT_LINE ('TOTAL NUMBER OF DIGITS IN THE GIVEN NUMBER '||NO1||' IS: '||CNT);
	END;

-- Q.6. TAKE A NUMBER AS FROM USER. DISPLAY THE NTH EVEN NUMBER AFTER THE USER INPUT
--      TAKE N FROM USER 

	SET SERVEROUTPUT ON
	DECLARE
		NO1 NUMBER := &NO1;
        N NUMBER := &N;
		CNT NUMBER := 0;
	BEGIN
    IF MOD(NO1,2) = 0
        THEN
            LOOP
			NO1 := NO1 + 2;
            CNT := CNT + 1;
            DBMS_OUTPUT.PUT_LINE (NO1);
		EXIT WHEN CNT = N;
		END LOOP;
        
    ELSE
            LOOP
			NO1 := NO1 + 1;
            CNT := CNT + 1;
            DBMS_OUTPUT.PUT_LINE (NO1);
		EXIT WHEN CNT = N;
		END LOOP;
    END IF;
    DBMS_OUTPUT.PUT_LINE ('THE '||N||'TH EVEN NUMBER IS: '||NO1);
	END;
	
-- Q.7. INCREASE THE SALARY BY 10% FOR THE EMPLOYEES WORKING IN DEPARTMENT 30 AND 
--      THEN DISPLAY NEW SALARY ALSO THE NEW MAXIMUM SALARY  

	SET SERVEROUTPUT ON
	DECLARE
		SAL NUMBER;
        NEW_SAL NUMBER;
        START_EMPID NUMBER := &EID  ;
        END_EMPID NUMBER := &EID;
        
	BEGIN
      
        LOOP
            SELECT SALARY INTO SAL
            FROM EMPLOYEES
            WHERE EMPLOYEE_ID =  START_EMPID; 
          
            NEW_SAL := SAL * 1.1;
            
            DBMS_OUTPUT.PUT_LINE('EMPLOYEE ID : '|| START_EMPID||'  SALARY : '|| SAL||'  NEW SALARY : '||NEW_SAL);
            START_EMPID :=  START_EMPID + 1;
            EXIT WHEN  START_EMPID >  END_EMPID;
        END LOOP;
	END;
		
	
