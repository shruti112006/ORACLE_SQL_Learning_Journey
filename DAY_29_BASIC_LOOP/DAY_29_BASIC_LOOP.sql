-- Q.1. FIBONACCI SERIES UPTO 10 NUMBERS
	
	SET SERVEROUTPUT ON
	DECLARE
		NO1 NUMBER := 0;
		NO2 NUMBER := 1;
		RSLT NUMBER ;
		I NUMBER := 0;
	BEGIN
		DBMS_OUTPUT.PUT_LINE(NO1);
		DBMS_OUTPUT.PUT_LINE(NO2);
		LOOP
			RSLT := NO1+ NO2;
			DBMS_OUTPUT.PUT_LINE(RSLT);
			NO1 := NO2;
			NO2 := RSLT;
			I := I + 1;
		EXIT WHEN I = 8;
		END LOOP;
	END;
	
-- Q.2 FACTORIAL OF A GIVEN NUMBER.
	
	SET SERVEROUTPUT ON
	DECLARE
		NO1 NUMBER := &N1;
		FACTO NUMBER := 1;
		I NUMBER := 1;
		
	BEGIN
		LOOP
			FACTO := FACTO * I;
			DBMS_OUTPUT.PUT_LINE (FACTO);
			I := I + 1;
			EXIT WHEN I > NO1;
		END LOOP;
		DBMS_OUTPUT.PUT_LINE ('THE FACTORIAL OF '||NO1||' IS: '||FACTO);
	END;
	
-- Q.3 TAKE 2 INPUT NUMBERS ,SUM OF NUMBERS BETWEEN THEM (INCLUDE STARTING NUM BUT EXCLUDE END NUMBER)

	SET SERVEROUTPUT ON
	DECLARE
		START_NO NUMBER := &S;
		END_NO NUMBER := &E;
		TOTAL NUMBER := 0 ;
	BEGIN
		LOOP 
			TOTAL := TOTAL + START_NO;
			DBMS_OUTPUT.PUT_LINE (TOTAL);
			START_NO := START_NO + 1;
			
		EXIT WHEN START_NO = END_NO;
		END LOOP;
		DBMS_OUTPUT.PUT_LINE ( 'TOTAL SUM IS : '|| TOTAL);
	END;
	
