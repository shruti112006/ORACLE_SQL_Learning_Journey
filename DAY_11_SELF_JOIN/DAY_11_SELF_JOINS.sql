-- 1. WAQD details like employye_id, employee fullname, manager name
	SELECT  M.EMPLOYEE_ID, CONCAT(CONCAT(M.FIRST_NAME,' '),M.LAST_NAME) AS EMP_NAME, 
			(E.FIRST_NAME||' '||E.LAST_NAME) AS MAN_NAME
	FROM EMPLOYEES E JOIN EMPLOYEES M
	ON (E.EMPLOYEE_ID = M.MANAGER_ID ) 

-- 2. WAQD total number of employees reporting to each manager

    SELECT M.MANAGER_ID , COUNT(E.EMPLOYEE_ID) AS EMP_COUNT
    FROM EMPLOYEES E JOIN EMPLOYEES M
    ON (E.EMPLOYEE_ID = M.MANAGER_ID)
    GROUP BY M.MANAGER_ID;
	
-- 3 .WAQD employees who have same job profession as their manager
    SELECT E.LAST_NAME AS EMPLOYEE,
           E.JOB_ID AS EMPLOYEE_JOB,
           M.LAST_NAME AS MANAGER,
           M.JOB_ID AS MANAGER_JOB
    FROM EMPLOYEES M
    JOIN EMPLOYEES E
    ON E.MANAGER_ID = M.EMPLOYEE_ID
    WHERE E.JOB_ID = M.JOB_ID;

-- 4 .WAQD employees who have same department as their manager
    SELECT E.EMPLOYEE_ID ,E.FIRST_NAME AS EMPLOYEE,
           E.DEPARTMENT_ID AS EMPLOYEE_DEPT,
           M.FIRST_NAME AS MANAGER,
           M.DEPARTMENT_ID AS MANAGER_DEPT
    FROM EMPLOYEES M
    JOIN EMPLOYEES E
    ON E.MANAGER_ID = M.EMPLOYEE_ID
    WHERE E.DEPARTMENT_ID = M.DEPARTMENT_ID;
	
-- 5. DISPLAY EMPLOYEES WHOSE COMMISSION IS LESS THAN THEIR MANAGER'S COMMISSION.
    
    SELECT E.EMPLOYEE_ID,
           E.LAST_NAME AS EMPLOYEE,
           E.COMMISSION_PCT AS EMPLOYEE_COMMISSION,
           M.LAST_NAME AS MANAGER,
           M.COMMISSION_PCT AS MANAGER_COMMISSION
    FROM EMPLOYEES E
    JOIN EMPLOYEES M
         ON E.MANAGER_ID = M.EMPLOYEE_ID
    WHERE E.COMMISSION_PCT < M.COMMISSION_PCT;
	
-- 6. DISPLAY EMPLOYEES WHOSE SALARY IS GREATER THAN THEIR MANAGER'S SALARY.
    
    SELECT E.EMPLOYEE_ID,
           CONCAT(CONCAT(E.FIRST_NAME,' '), E.LAST_NAME) AS EMPLOYEE,
           E.SALARY AS EMPLOYEE_SAL,
           CONCAT(CONCAT(M.FIRST_NAME,' '), M.LAST_NAME)  AS MANAGER_NAME,
           M.SALARY AS MANAGER_SAL
    FROM EMPLOYEES E
    JOIN EMPLOYEES M
         ON E.MANAGER_ID = M.EMPLOYEE_ID
    WHERE E.SALARY > M.SALARY;
	
-- 7. DISPLAY EMPLOYEES REPORTING TO MANAGER WHOSE MANAGER ID IS GREATER THAN 140 AND
--    HAVING EMPLOYEE COUNT GREATER THAN 5
    
    SELECT E.MANAGER_ID , COUNT(M.EMPLOYEE_ID) AS EMP_COUNT
    FROM EMPLOYEES E
    JOIN EMPLOYEES M
         ON E.MANAGER_ID = M.EMPLOYEE_ID
    WHERE E.MANAGER_ID > 140
    GROUP BY E.MANAGER_ID
    HAVING COUNT(M.EMPLOYEE_ID) > 5 ;
	
-- 8. DISPLAY NAME OF MANAGER WHOSE NAME STARTS WITH A
     
    SELECT E.EMPLOYEE_ID, CONCAT(CONCAT(M.FIRST_NAME ,' '),M.LAST_NAME) AS MANAGER_NAME 
    FROM EMPLOYEES E
    JOIN EMPLOYEES M
    ON E.MANAGER_ID = M.EMPLOYEE_ID
    WHERE M.FIRST_NAME LIKE 'A%';
  
-- 9. DISPLAY NAME OF EMPLOYEES WHOSE MANAGER JOINED IN 2006
     
    SELECT  M.EMPLOYEE_ID, CONCAT(CONCAT(M.FIRST_NAME ,' '),M.LAST_NAME) AS EMP_NAME, M.HIRE_DATE AS EMP_JOINED,
            E.EMPLOYEE_ID AS MGR_ID, E.HIRE_DATE AS MGR_JOINED
    FROM EMPLOYEES E
    JOIN EMPLOYEES M
    ON M.MANAGER_ID = E.EMPLOYEE_ID
    WHERE TO_CHAR(E.HIRE_DATE,'YYYY') = '2006';
	
-- 10 .WAQD employees who have different job profession than their manager
    SELECT E.LAST_NAME AS EMPLOYEE,
           E.JOB_ID AS EMPLOYEE_JOB,
           M.LAST_NAME AS MANAGER,
           M.JOB_ID AS MANAGER_JOB
    FROM EMPLOYEES M
    JOIN EMPLOYEES E
    ON E.MANAGER_ID = M.EMPLOYEE_ID
    WHERE E.JOB_ID <> M.JOB_ID
	
