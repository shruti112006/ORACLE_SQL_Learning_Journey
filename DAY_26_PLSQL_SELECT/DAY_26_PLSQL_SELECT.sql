-- Q.6.SELECT JOIN INTO
    
    SET SERVEROUTPUT ON
    DECLARE
        EID NUMBER;
        SAL NUMBER;
        DID NUMBER;
        DNAME VARCHAR2(20);
        CITY VARCHAR2(10);
    BEGIN
        SELECT E.EMPLOYEE_ID, E.SALARY, D.DEPARTMENT_ID, D.DEPARTMENT_NAME, L.CITY
        INTO EID, SAL, DID, DNAME, CITY 
        FROM EMPLOYEES E RIGHT OUTER JOIN DEPARTMENTS D
        ON (E.DEPARTMENT_ID = D.DEPARTMENT_ID)
        JOIN LOCATIONS L
        ON(L.LOCATION_ID= D.LOCATION_ID)
        WHERE UPPER(DEPARTMENT_NAME) = &DNAME;

-- Q.7.  SELECT SUBQUERY INTO
    SET SERVEROUTPUT ON 
    DECLARE
        EID NUMBER;
        DID NUMBER;
        DNAME VARCHAR2(20);
        CITY VARCHAR2(10);
        SAL NUMBER;
    BEGIN
        SELECT E.EMPLOYEE_ID, E.SALARY, D.DEPARTMENT_ID, D.DEPARTMENT_NAME, L.CITY
        INTO EID, SAL, DID, DNAME, CITY 
        FROM EMPLOYEES E JOIN DEPARTMENTS D
        ON (E.DEPARTMENT_ID = D.DEPARTMENT_ID)
        JOIN LOCATIONS L
        ON(L.LOCATION_ID= D.LOCATION_ID)
        WHERE L.LOCATION_ID = (   SELECT LOCATION_ID FROM DEPARTMENTS
                                  WHERE  UPPER(DEPARTMENT_NAME) = 'HUMAN RESOURCES' );
    
        DBMS_OUTPUT.PUT_LINE('EMPLOYEE_ID  SALARY  DEPARTMENT_ID  DEPARTMENT_NAME         CITY');

        DBMS_OUTPUT.PUT_LINE(' '||EID ||'        '||SAL||'            '||DID||'        '|| DNAME ||'       '||CITY );
    END;
 
