-- Q.9. SELECT CASE INTO

	SET SERVEROUTPUT ON
	DECLARE
		EID       NUMBER;
		FNAME     VARCHAR2(50);
		LNAME     VARCHAR2(50);
		WEEK_DAY  VARCHAR2(10);
		DAY_TYPE  VARCHAR2(10);
	BEGIN
		SELECT employee_id,
			   first_name,
			   last_name,
			   TO_CHAR(hire_date,'DY') AS week_day,
			   CASE 
				   WHEN TO_CHAR(hire_date,'DY') IN ('SAT','SUN') THEN 'WEEKEND'
				   ELSE 'WEEKDAY'
			   END AS day_type
		INTO EID, FNAME, LNAME, WEEK_DAY, DAY_TYPE
		FROM employees
		WHERE employee_id = &EMP_ID;  -- Ask user for employee ID

		-- Print the details
		DBMS_OUTPUT.PUT_LINE('Employee ID: ' || EID);
		DBMS_OUTPUT.PUT_LINE('Name: ' || FNAME || ' ' || LNAME);
		DBMS_OUTPUT.PUT_LINE('Day of Hire: ' || WEEK_DAY);
		DBMS_OUTPUT.PUT_LINE('Type of Day: ' || DAY_TYPE);
	END;
	
-- Q.10.  SELECT AGGREGATE INTO

    SET SERVEROUTPUT ON 
    DECLARE
        DID NUMBER;
        DNAME VARCHAR2(20);
        EMP_CNT NUMBER;
    BEGIN
        SELECT D.DEPARTMENT_ID, D.DEPARTMENT_NAME, COUNT (*) 
        INTO DID, DNAME, EMP_CNT
        FROM EMPLOYEES E JOIN DEPARTMENTS D
        ON (E.DEPARTMENT_ID = D.DEPARTMENT_ID)
      
        WHERE D. DEPARTMENT_ID = &DID
        GROUP BY D.DEPARTMENT_ID, D.DEPARTMENT_NAME;
    
        DBMS_OUTPUT.PUT_LINE('  DEPARTMENT_ID      DEPARTMENT_NAME       COUNT');

        DBMS_OUTPUT.PUT_LINE('     '||DID||'             '|| DNAME ||'                '||EMP_CNT );
    END;
    
    
    
  

